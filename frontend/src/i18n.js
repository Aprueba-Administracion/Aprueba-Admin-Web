// Devuelve la traducción de `k` sustituyendo los marcadores {var} por `vars`.
export function makeL(lang) {
  return (k, vars) => {
    const raw = (T[lang] && T[lang][k]) || T.es[k] || k;
    if (!vars) return raw;
    return String(raw).replace(/\{(\w+)\}/g, (m, name) => (vars[name] != null ? String(vars[name]) : m));
  };
}
export function fmt(n, lang) {
  return Number(n || 0).toLocaleString(lang === 'es' ? 'es-CL' : 'en-US');
}
